/**
 * Pass 2 — Graphify refresh runner.
 *
 * Regenerates `d:\Veilpay\graphify-out\` (or whatever `graphifyOutDir` the
 * orchestrator points us at) and produces a structured
 * `GraphifyRefreshSummary` consumed by Pass 4 (Reporting). Every spawn goes
 * through `runCommand` so evidence and failure-capture invariants are
 * uniform with the rest of Pass 2 (Property 14).
 *
 * Implements:
 *   - Requirement 3.1: Run the Graphify_Pipeline against the workspace root.
 *   - Requirement 3.2: Verify regeneration of GRAPH_REPORT.md, graph.json,
 *     and manifest.json.
 *   - Requirement 3.3: When `wiki/index.md` exists, verify it regenerated.
 *   - Requirement 3.4: Parse the top three architectural observations
 *     verbatim from GRAPH_REPORT.md.
 *   - Requirement 3.5: Record the run timestamp in ISO 8601.
 *   - Requirement 3.6 / Property 14: failure_capture is non-null iff exit
 *     code is non-zero, with command, exit code, and the last 50 lines of
 *     output bounded by the `runCommand` harness.
 *
 * Cache-stale fallback:
 *   The Graphify CLI sometimes short-circuits a `graphify .` invocation
 *   when its on-disk cache thinks nothing changed, in which case
 *   `wiki/index.md` is left stale even though the command exits 0. We
 *   detect this by comparing `wiki/index.md`'s mtime against the
 *   pre-spawn timestamp; if stale we re-run with `--update` to force a
 *   full rebuild (this matches the workspace `AGENTS.md` Graphify
 *   guidance: "If the graph is missing or stale, run `graphify .` or
 *   `graphify --update` first.").
 */

import { promises as fs } from 'node:fs';
import * as path from 'node:path';

import type {
  FailureCapture,
  GraphifyRefreshSummary,
} from '../../models';

import { MAX_TAIL_LINES, runCommand, type EvidenceRecord } from './runner';

/**
 * Sentinel inserted into `top_observations` when GRAPH_REPORT.md does not
 * yield enough parseable bullet/observation lines to fill the required
 * 3-tuple (Requirement 3.4). The literal is part of the contract with the
 * Pass 4 renderer so reviewers can immediately spot a thin observations
 * section without reading the raw Graphify output.
 */
export const OBSERVATION_NOT_PRESENT = 'observation not present' as const;

/**
 * Inputs required by `runGraphify`. Everything is an absolute path so the
 * runner does not have to guess about working directories.
 */
export interface RunGraphifyInput {
  /** Absolute path to the workspace root, e.g., `d:\Veilpay`. */
  readonly workspaceRoot: string;
  /** Absolute path to the Graphify output directory, e.g., `d:\Veilpay\graphify-out`. */
  readonly graphifyOutDir: string;
  /**
   * Absolute path to the Pass 2 evidence directory, typically
   * `d:\Veilpay\plans\.audit-evidence`. The graphify run's combined output
   * is written to `<evidenceDir>\graphify.txt` (and, on fallback, also
   * `<evidenceDir>\graphify-update.txt`) by `runCommand`.
   */
  readonly evidenceDir: string;
}

/**
 * Run Graphify and assemble the summary section consumed by Pass 4.
 *
 * The high-level flow:
 *   1. Capture `runStartedAt` *before* spawning so freshness checks have a
 *      monotonic floor.
 *   2. Run `graphify .` from `workspaceRoot` via `runCommand`.
 *   3. If exit code is non-zero OR `wiki/index.md` exists but its mtime is
 *      older than `runStartedAt`, fall back to `graphify --update`.
 *   4. On success, verify GRAPH_REPORT.md / graph.json / manifest.json
 *      exist and have mtime ≥ `runStartedAt`. If `wiki/index.md` exists,
 *      verify it too.
 *   5. Parse the top three observations from GRAPH_REPORT.md, padding with
 *      `OBSERVATION_NOT_PRESENT` when fewer than three exist.
 *   6. Build the `GraphifyRefreshSummary`. `failure_capture` is non-null
 *      iff the final invocation exited non-zero.
 *
 * On final-invocation failure the function does NOT throw; it returns a
 * summary whose `failure_capture` is populated and whose `top_observations`
 * is filled with `OBSERVATION_NOT_PRESENT` so the report renderer can still
 * emit a stable section. Callers (Pass 4) decide how to surface that to
 * the report verdict.
 */
export async function runGraphify(
  input: RunGraphifyInput,
): Promise<GraphifyRefreshSummary> {
  const { workspaceRoot, graphifyOutDir, evidenceDir } = input;

  // Floor for "fresh enough to count as regenerated by this run". Captured
  // before any spawn so we never accept a file that pre-existed unchanged.
  const runStartedAt = new Date();
  // Truncate the floor down by one millisecond. Some filesystems (notably
  // FAT-derived ones on Windows) round mtime to the nearest second, which
  // can cause a freshly-written file to report a timestamp slightly older
  // than the one we recorded immediately before spawning. The 1 ms slack
  // keeps the freshness check from rejecting such files.
  const freshnessFloor = runStartedAt.getTime() - 1000;

  const wikiIndexPath = path.join(graphifyOutDir, 'wiki', 'index.md');

  // ------------------------------------------------------------------
  // Step 2: graphify .
  // ------------------------------------------------------------------
  const primaryEvidence = path.join(evidenceDir, 'graphify.txt');
  const primary = await runCommand(
    'graphify',
    ['.'],
    primaryEvidence,
    { cwd: workspaceRoot },
  );

  // ------------------------------------------------------------------
  // Step 3: cache-stale or hard-failure fallback to graphify --update.
  // ------------------------------------------------------------------
  const wikiPresent = await pathExists(wikiIndexPath);
  const wikiStale =
    wikiPresent && !(await mtimeAtLeast(wikiIndexPath, freshnessFloor));
  const shouldFallback = primary.exitCode !== 0 || wikiStale;

  let finalRun: EvidenceRecord = primary;
  if (shouldFallback) {
    const fallbackEvidence = path.join(evidenceDir, 'graphify-update.txt');
    finalRun = await runCommand(
      'graphify',
      ['--update'],
      fallbackEvidence,
      { cwd: workspaceRoot },
    );
  }

  // The run timestamp recorded in the summary reflects when the *last*
  // invocation completed (or, more precisely, when the runner returned).
  // We use a fresh `new Date()` here per the task brief.
  const runAtIso = new Date().toISOString();

  // ------------------------------------------------------------------
  // Step 6 (early): hard failure on the final invocation.
  // ------------------------------------------------------------------
  // If the final invocation exited non-zero, populate failure_capture and
  // skip artifact verification + observation parsing — both would just
  // produce noise. The renderer needs a stable shape, so we still pad the
  // observations tuple with the sentinel.
  if (finalRun.exitCode !== 0) {
    return buildFailedSummary({
      finalRun,
      workspaceRoot,
      graphifyOutDir,
      runAtIso,
    });
  }

  // ------------------------------------------------------------------
  // Step 4: verify regeneration of required artifacts.
  // ------------------------------------------------------------------
  const requiredArtifacts: readonly string[] = [
    path.join(graphifyOutDir, 'GRAPH_REPORT.md'),
    path.join(graphifyOutDir, 'graph.json'),
    path.join(graphifyOutDir, 'manifest.json'),
  ];
  for (const artifactPath of requiredArtifacts) {
    await assertRegenerated(artifactPath, freshnessFloor);
  }
  if (await pathExists(wikiIndexPath)) {
    await assertRegenerated(wikiIndexPath, freshnessFloor);
  }

  // ------------------------------------------------------------------
  // Step 5: parse top three observations from GRAPH_REPORT.md.
  // ------------------------------------------------------------------
  const reportPath = path.join(graphifyOutDir, 'GRAPH_REPORT.md');
  const reportContents = await fs.readFile(reportPath, 'utf8');
  const observations = parseTopObservations(reportContents);

  return buildGraphifySummaryFromRecord(finalRun, {
    workspaceRoot,
    graphifyOutDir,
    runAtIso,
    observations,
  });
}

